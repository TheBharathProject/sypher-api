// buildCoverLetterPDF creates a formatted cover letter PDF from text parts.
// Uses Helvetica (built-in, no font file required) with UnicodeTranslator for
// common Latin-extended characters. Returns the Fpdf object; caller streams it.
func buildCoverLetterPDF(text, company, role string) (*fpdf.Fpdf, error) {
	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.SetMargins(25, 25, 25)
	pdf.SetAutoPageBreak(true, 20)
	pdf.AddPage()

	tr := pdf.UnicodeTranslatorFromDescriptor("")
	pageW, _ := pdf.GetPageSize()
	bodyW := pageW - 50 // left(25) + right(25)

	// Header: Company (bold 14pt)
	pdf.SetFont("Helvetica", "B", 14)
	lineH := pdf.PointConvert(14)
	if company != "" {
		pdf.MultiCell(bodyW, lineH, tr(company), "", "L", false)
		pdf.Ln(2)
	}

	// Subtitle: Role (regular 12pt)
	pdf.SetFont("Helvetica", "", 12)
	lineH12 := pdf.PointConvert(12)
	if role != "" {
		pdf.MultiCell(bodyW, lineH12, tr(role), "", "L", false)
		pdf.Ln(2)
	}

	// Date line
	pdf.SetFont("Helvetica", "", 10)
	lineH10 := pdf.PointConvert(10)
	pdf.MultiCell(bodyW, lineH10, time.Now().Format("2 January 2006"), "", "L", false)
	pdf.Ln(6)

	// Body: cover letter text (11pt)
	pdf.SetFont("Helvetica", "", 11)
	lineH11 := pdf.PointConvert(11) * 1.4
	pdf.MultiCell(bodyW, lineH11, tr(text), "", "L", false)

	// Footer
	pdf.SetY(-20)
	pdf.SetFont("Helvetica", "I", 8)
	pdf.MultiCell(bodyW, pdf.PointConvert(8), "Generated by Pegasus · sypher.in/pegasus", "", "C", false)

	if err := pdf.Error(); err != nil {
		return nil, fmt.Errorf("build cover letter pdf: %w", err)
	}
	return pdf, nil
}

