// ResumeTweakPDF streams a PDF for an existing resume tweak row.
// Uses UserEdits when non-empty, otherwise TweakedText.
// No credits debited — PDF is free export of already-generated content.
func (h *Handler) ResumeTweakPDF(w http.ResponseWriter, r *http.Request) {
	uid := auth.MustUserID(r.Context())
	tweakID, ok := pathUUID(w, r, "id")
	if !ok {
		return
	}

	tweak, err := h.store.GetResumeTweak(r.Context(), uid, tweakID)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			httpx.WriteError(w, http.StatusNotFound, "not_found", "resume tweak not found")
			return
		}
		writeDBError(w, err)
		return
	}

	bodyText := tweak.UserEdits
	if bodyText == "" {
		bodyText = tweak.TweakedText
	}

	title := tweak.Title
	if title == "" {
		title = "Untitled"
	}

	pdf, err := buildTweakPDF(title, bodyText)
	if err != nil {
		h.logger.Error("build tweak pdf", "err", err)
		httpx.WriteError(w, http.StatusInternalServerError, "internal_error", "could not generate PDF")
		return
	}

	filename := sanitizeFilename(fmt.Sprintf("resume-tweak-%s.pdf", tweakID.String()[:8]))
	streamPDF(w, pdf, filename)
}

