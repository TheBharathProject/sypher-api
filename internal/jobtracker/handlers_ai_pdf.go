// unsafeFilenameChars matches any character that is not alphanumeric,
// a hyphen, underscore, or dot. Used to sanitize Content-Disposition filenames.
var unsafeFilenameChars = regexp.MustCompile(`[^a-zA-Z0-9._\-]`)

// sanitizeFilename strips unsafe characters from a filename, replaces them
// with hyphens, collapses consecutive hyphens, trims leading/trailing hyphens,
// and truncates at 200 characters.
func sanitizeFilename(name string) string {
	name = strings.TrimSpace(name)
	name = unsafeFilenameChars.ReplaceAllString(name, "-")
	// Collapse consecutive hyphens.
	for strings.Contains(name, "--") {
		name = strings.ReplaceAll(name, "--", "-")
	}
	name = strings.Trim(name, "-")
	if len(name) > 200 {
		name = name[:200]
	}
	if name == "" {
		name = "download.pdf"
	}
	return name
}

