// stripMarkdown performs a best-effort strip of common markdown syntax so the
// text reads cleanly in a PDF. It handles headings, bold/italic, code fences,
// and horizontal rules.
var (
	mdHeading   = regexp.MustCompile(`(?m)^#{1,6}\s+`)
	mdBoldItal  = regexp.MustCompile(`\*{1,3}([^*]+)\*{1,3}`)
	mdCodeFence = regexp.MustCompile("(?m)^```[^\\n]*\\n?")
	mdInlineCode = regexp.MustCompile("`([^`]+)`")
	mdHRule     = regexp.MustCompile(`(?m)^[-*_]{3,}\s*$`)
)

func stripMarkdown(md string) string {
	s := mdHeading.ReplaceAllString(md, "")
	s = mdBoldItal.ReplaceAllString(s, "$1")
	s = mdCodeFence.ReplaceAllString(s, "")
	s = mdInlineCode.ReplaceAllString(s, "$1")
	s = mdHRule.ReplaceAllString(s, "")
	return strings.TrimSpace(s)
}

// streamPDF sets Content-Type / Content-Disposition headers and writes the PDF
// bytes to w. Headers must be set before Output writes the first byte.
// If Output errors after headers are committed, we log via the package-level
// slog default logger (the only logger available at this scope).
func streamPDF(w http.ResponseWriter, pdf *fpdf.Fpdf, filename string) {
	w.Header().Set("Content-Type", "application/pdf")
	w.Header().Set("Content-Disposition", fmt.Sprintf(`attachment; filename="%s"`, filename))
	if err := pdf.Output(w); err != nil {
		// Headers are already committed; we can only log — cannot send a JSON error.
		slog.Error("pdf output", "err", err)
	}
}

// ----------------------------------------------------------------------------
// Handler: CoverLetterPDF
// POST /job-tracker/ai/cover-letter/pdf
// ----------------------------------------------------------------------------

type coverLetterPDFInput struct {
	Text    string `json:"text"`
	Company string `json:"company"`
	Role    string `json:"role"`
}

// CoverLetterPDF streams a PDF of the supplied cover letter text.
// No credits are debited — credits were consumed at text-generation time.
func (h *Handler) CoverLetterPDF(w http.ResponseWriter, r *http.Request) {
	var in coverLetterPDFInput
	if !readJSON(w, r, &in) {
		return
	}
	if strings.TrimSpace(in.Text) == "" {
		httpx.WriteError(w, http.StatusBadRequest, "bad_input", "text is required")
		return
	}

	pdf, err := buildCoverLetterPDF(in.Text, in.Company, in.Role)
	if err != nil {
		h.logger.Error("build cover letter pdf", "err", err)
		httpx.WriteError(w, http.StatusInternalServerError, "internal_error", "could not generate PDF")
		return
	}

	filename := sanitizeFilename(fmt.Sprintf("%s-%s-cover-letter.pdf", in.Company, in.Role))
	streamPDF(w, pdf, filename)
}

