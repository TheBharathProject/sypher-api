	pdf.SetFont("Helvetica", "B", 16)
	lineH16 := pdf.PointConvert(16)
	pdf.MultiCell(bodyW, lineH16, "Resume Analysis Report", "", "L", false)
	pdf.Ln(2)

	// Date subtitle (regular 12pt)
